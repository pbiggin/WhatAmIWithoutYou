function updateCardText(targetOrText, maybeText) {
  if (typeof targetOrText === "string") {
    messageEl.textContent = targetOrText;
    return;
  }
  const text = typeof maybeText === "string" ? maybeText : "";
  const spokenEl =
    targetOrText && targetOrText.querySelector
      ? targetOrText.querySelector(".spoken")
      : messageEl;
  if (spokenEl) spokenEl.textContent = text;
}

