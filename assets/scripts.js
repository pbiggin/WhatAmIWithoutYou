function cloneTab(newId) {
  const original = document.getElementById("drag");
  if (!original) return null;

  const clone = original.cloneNode(true);
  clone.id = newId;

  // ensure unique header id
  const header = clone.querySelector("header");
  if (header) header.id = `${newId}header`;

  // clear spoken text
  const spoken = clone.querySelector(".spoken");
  if (spoken) spoken.textContent = "";

  // copy class and set size
  clone.className = original.className;
  clone.style.position = "absolute";
  clone.style.width = original.offsetWidth + "px";
  clone.style.height = original.offsetHeight + "px";

  // random position within viewport bounds
  const maxLeft = Math.max(0, window.innerWidth - original.offsetWidth - 10);
  const maxTop = Math.max(0, window.innerHeight - original.offsetHeight - 10);
  const randomLeft = Math.floor(Math.random() * maxLeft);
  const randomTop = Math.floor(Math.random() * maxTop);

  clone.style.left = randomLeft + "px";
  clone.style.top = randomTop + "px";

  clone.tabIndex = 0;
  document.body.appendChild(clone);
  dragElement(clone);
  return clone;
}

async function askQuestion(
  question,
  options = ["yes", "no"],
  tab = document.getElementById("drag"),
  showTimer = false,
) {
  if (!tab) return null;
  updateCardText(tab, question);

  const existingButtons = tab.querySelector(".choice-buttons");
  if (existingButtons) existingButtons.remove();

  const choiceConfig = Array.isArray(options)
    ? { type: "buttons", choices: options }
    : typeof options === "object" && options !== null
      ? { type: options.type || "buttons", ...options }
      : { type: "buttons", choices: [String(options)] };

  const container = document.createElement("div");
  container.className = "choice-buttons";
  tab.appendChild(container);

  let timerInterval = null;
  let startTime = Date.now();
  const persistentTimer = showTimer === "persistent";
  const showTimerBool = Boolean(showTimer);

  const timerDisplay = document.createElement("div");
  timerDisplay.className = "timer-display";
  timerDisplay.style.fontSize = "16px";
  timerDisplay.style.color = "var(--primary--colour)";
  timerDisplay.style.marginBottom = "0.5rem";
  timerDisplay.style.textAlign = "center";

  if (showTimerBool) {
    container.appendChild(timerDisplay);
    timerInterval = setInterval(() => {
      const elapsed = ((Date.now() - startTime) / 1000).toFixed(2);
      timerDisplay.textContent = `Time: ${elapsed}s`;
    }, 50);
  }

  return new Promise((resolve) => {
    const finish = (value) => {
      if (timerInterval) clearInterval(timerInterval);
      const finalTime = ((Date.now() - startTime) / 1000).toFixed(2);
      if (showTimer) {
        timerDisplay.textContent = `${finalTime}s`;
      }
      setTimeout(
        () => {
          // If timer was shown and not persistent, clear it and remove display.
          if (timerInterval && !persistentTimer) clearInterval(timerInterval);
          if (!persistentTimer) container.remove();

          if (showTimerBool) {
            if (persistentTimer) {
              // return a clear function so caller can remove the timer later
              const clearTimer = () => {
                if (timerInterval) {
                  clearInterval(timerInterval);
                  timerInterval = null;
                }
                if (timerDisplay && timerDisplay.parentNode) {
                  timerDisplay.parentNode.removeChild(timerDisplay);
                }
              };
              resolve({ value, time: Number(finalTime), clearTimer });
            } else {
              resolve({ value, time: Number(finalTime) });
            }
          } else {
            resolve(value);
          }
        },
        showTimerBool ? 800 : 0,
      );
    };

    if (choiceConfig.type === "text" || choiceConfig.type === "textarea") {
      const input = document.createElement(
        choiceConfig.type === "textarea" ? "textarea" : "input",
      );
      input.type = choiceConfig.inputType || "text";
      input.placeholder = choiceConfig.placeholder || "Type your answer...";
      input.className = "question-input";
      input.style.width = "100%";
      input.style.marginBottom = "0.5rem";

      const submit = document.createElement("button");
      submit.type = "button";
      submit.textContent = choiceConfig.submitLabel || "Submit";
      submit.className = "option-btn";

      submit.onclick = () => {
        const value = input.value;
        if (value !== "" || choiceConfig.allowEmpty) {
          finish(value);
        }
      };

      input.addEventListener("keydown", (event) => {
        if (event.key === "Enter" && choiceConfig.submitOnEnter !== false) {
          event.preventDefault();
          submit.click();
        }
      });

      container.appendChild(input);
      container.appendChild(submit);
      input.focus();
      return;
    }

    const buttons = document.createElement("div");
    buttons.className = "button-options";
    buttons.innerHTML = (choiceConfig.choices || [])
      .map(
        (option, index) =>
          `<button class="option-btn option-${index}">${option}</button>`,
      )
      .join("\n");
    container.appendChild(buttons);

    const buttonEls = buttons.querySelectorAll("button");
    buttonEls.forEach((button, index) => {
      button.onclick = () => finish(choiceConfig.choices[index]);
    });
  });
}

