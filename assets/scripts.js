function skipToEvent(index) {
  const raw = Number(index);
  if (Number.isNaN(raw)) return;

  const target = raw >= 1 && raw <= events.length ? raw - 1 : raw;
  if (target < 0 || target >= events.length) return;

  currentEvent = target;
  runNextEvent();
}

function runNextEvent() {
  if (currentEvent >= events.length) return;
  const next = events[currentEvent];
  currentEvent += 1;
  next(runNextEvent);
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function waitForFocus() {
  return new Promise((resolve) => {
    if (document.hasFocus() && document.visibilityState === "visible") {
      resolve();
      return;
    }

    function onFocus() {
      window.removeEventListener("focus", onFocus);
      resolve();
    }

    window.addEventListener("focus", onFocus, { once: true });
  });
}

function waitForBlur() {
  return new Promise((resolve) => {
    function onBlur() {
      window.removeEventListener("blur", onBlur);
      clearTimeout(timeoutId);
      resolve();
    }

    // Auto-resolve after 10 seconds if blur doesn't happen (for testing)
    const timeoutId = setTimeout(() => {
      window.removeEventListener("blur", onBlur);
      resolve();
    }, 10000);

    window.addEventListener("blur", onBlur, { once: true });
  });
}

